import { shellQuote } from "@/lib/shell-quote";

/** The lock is outside the installation directory so replacing it cannot split the lock. */
export function withLinuxAgentInstallLock(script: string) {
  const lock = [
    "import fcntl, os, sys",
    "lock = open('/run/vcontrolhub-agent-lifecycle.lock', 'a')",
    "fcntl.flock(lock, fcntl.LOCK_EX)",
    "os.set_inheritable(lock.fileno(), True)",
    "os.execl('/bin/sh', 'sh', '-c', sys.argv[1])",
  ].join("\n");
  return `python3 -c ${shellQuote(lock)} ${shellQuote(script)}`;
}

export function withWindowsAgentInstallLock(script: string) {
  return [
    "$mutex = [Threading.Mutex]::new($false, 'Global\\VControlHubAgentLifecycle')",
    "$held = $false",
    "try {",
    "  try { $held = $mutex.WaitOne(30000) } catch [Threading.AbandonedMutexException] { $held = $true }",
    "  if (-not $held) { throw 'Another Agent installation or removal is in progress' }",
    script,
    "} finally {",
    "  if ($held) { $mutex.ReleaseMutex() }",
    "  $mutex.Dispose()",
    "}",
  ].join("\n");
}

// A legacy installation has no identity file. All replacement installers write
// it while holding the same host lock as the delayed cleanup.
export function guardedLinuxAgentRemoval(identity: string | null, cleanup: string) {
  return withLinuxAgentInstallLock([
    'stamp=/opt/vcontrolhub-agent/install-id',
    `if [ -e "$stamp" ]; then installed=$(cat "$stamp") || exit 1; [ "$installed" = ${shellQuote(identity ?? "unregistered")} ] || exit 1; fi`,
    cleanup,
  ].join("\n"));
}

export function linuxAgentSelfRemoval(identity: string) {
  const cleanup = [
    "systemctl disable vcontrolhub-agent.service >/dev/null 2>&1 || true",
    "rm -f /etc/systemd/system/vcontrolhub-agent.service",
    "rm -rf /opt/vcontrolhub-agent",
    "systemctl daemon-reload",
    "systemctl stop vcontrolhub-agent.service",
  ].join("\n");
  return `nohup sh -c ${shellQuote("sleep 2\n" + guardedLinuxAgentRemoval(identity, cleanup))} >/dev/null 2>&1 &`;
}

export function windowsAgentSelfRemoval(taskName: string, identity: string) {
  // Digest and task name are generated by the Hub. Escape PowerShell string literals.
  const literal = (value: string) => "'" + value.replaceAll("'", "''") + "'";
  const cleanup = withWindowsAgentInstallLock([
    "$ErrorActionPreference = 'Stop'",
    "$dir = Join-Path $env:ProgramData 'VControlHub'",
    "$stamp = Join-Path $dir 'install-id'",
    `if ((Test-Path -LiteralPath $stamp) -and (Get-Content -LiteralPath $stamp -Raw).Trim() -ne ${literal(identity)}) { return }`,
    `$taskName = ${literal(taskName)}`,
    "Stop-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue",
    "Unregister-ScheduledTask -TaskName $taskName -Confirm:$false",
    "Remove-Item -LiteralPath (Join-Path $dir 'agent.ps1') -Force",
    "if (Test-Path -LiteralPath $stamp) { Remove-Item -LiteralPath $stamp -Force }",
    "if (-not (Get-ChildItem -LiteralPath $dir -Force)) { Remove-Item -LiteralPath $dir }",
  ].join("\n"));
  const child = Buffer.from("Start-Sleep -Seconds 3\n" + cleanup, "utf16le").toString("base64");
  return `powershell -NoProfile -Command "Start-Process -WindowStyle Hidden powershell.exe -ArgumentList '-NoProfile','-NonInteractive','-EncodedCommand','${child}'"`;
}
