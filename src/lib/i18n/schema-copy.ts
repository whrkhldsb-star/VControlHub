/** Whether this message is one a schema author wrote (and so names its own subject, unlike the library's). */
export function isSchemaSentence(message: string): boolean {
	return Object.hasOwn(SCHEMA_COPY_ZH, message);
}

export function localizeSchemaMessage(message: string, locale: Locale): string {
	return locale === "zh" && isSchemaSentence(message) ? SCHEMA_COPY_ZH[message]! : message;
}

// For the error helper shared with the browser, which does not import this module (see ambient-locale.ts).
registerSchemaSentences(localizeSchemaMessage);

/**
 * The first refusal of a failed parse as a sentence, in the language text is being written in (the request's
 * on the server, the page's in the browser); undefined when the error carries none.
 */
export function firstSchemaSentence(error: { issues: ReadonlyArray<{ message?: unknown }> }): string | undefined {
	const message = error.issues[0]?.message;
	return typeof message === "string" && message ? localizeSchemaMessage(message, ambientCopyLocale() ?? "en") : undefined;
}
